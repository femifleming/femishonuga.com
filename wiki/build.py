#!/usr/bin/env python3
"""Wiki builder for femishonuga.com.

Reads wiki/lexicon.txt (the list of wiki pages and how they nest) and:
  1. rewrites the <nav>...</nav> sidebar in every wiki page listed there,
  2. rewrites the page tree on wiki/sitemap.html,
  3. reports broken links and wiki pages missing from the lexicon.

Run it from anywhere:   python3 wiki/build.py
It only edits HTML files in place. There is no output folder; push as usual.
See wiki/README.md for how to use it.
"""
import html
import os
import posixpath
import re
import sys
from urllib.parse import unquote

WIKI = os.path.dirname(os.path.abspath(__file__))
LEXICON = os.path.join(WIKI, 'lexicon.txt')
SITEMAP = 'sitemap.html'
HOME = 'index.html'
SITEMAP_START = '<!-- sitemap: generated by build.py, edit lexicon.txt instead -->'
SITEMAP_END = '<!-- /sitemap -->'


# ---------------------------------------------------------------- lexicon

class Entry:
    def __init__(self, href, label, long_label, parent, line, alias=False, hidden=False):
        self.alias = alias            # "= file.html" line: extra link, not the page's home
        self.hidden = hidden          # "~ file.html" line: on the sitemap, not in sidebars
        self.href = href              # path relative to wiki/, may include #anchor
        self.label = label            # short label, used in sidebars
        self.long_label = long_label  # label used on the sitemap
        self.parent = parent
        self.children = []            # Entry or Heading
        self.line = line

    @property
    def path(self):
        return posixpath.normpath(self.href.split('#')[0])


class Heading:
    def __init__(self, text):
        self.text = text


def fail(msg):
    print('ERROR: ' + msg)
    print('Nothing was changed.')
    sys.exit(1)


def read_lexicon():
    entry_re = re.compile(r'^(\S.*?\.[A-Za-z0-9]{2,5}(?:#\S*)?)(?=\s|$)\s*(.*)$')
    roots, stack = [], []   # stack of (indent, Entry)
    for num, raw in enumerate(open(LEXICON, encoding='utf-8'), 1):
        line = raw.rstrip('\n').expandtabs(4)
        text = line.strip()
        if not text or text.startswith('#'):
            continue
        indent = len(line) - len(line.lstrip(' '))
        while stack and stack[-1][0] >= indent:
            stack.pop()
        parent = stack[-1][1] if stack else None
        if text.startswith(':'):
            if parent is None:
                fail(f'lexicon.txt line {num}: a ": heading" line needs to be indented under a page.')
            parent.children.append(Heading(text[1:].strip()))
            continue
        alias = hidden = False
        while text[:1] in ('=', '~'):
            alias = alias or text[0] == '='
            hidden = hidden or text[0] == '~'
            text = text[1:].strip()
        m = entry_re.match(text)
        if not m:
            fail(f'lexicon.txt line {num}: expected "file.html  label", got: {text}')
        href, label = m.group(1), (m.group(2) or '').strip()
        if '|' in label:
            short, long_ = (s.strip() for s in label.split('|', 1))
        else:
            short = long_ = label
        if not short:
            short = long_ = posixpath.splitext(posixpath.basename(href.split('#')[0]))[0]
        e = Entry(href, short, long_ or short, parent, num, alias, hidden)
        (parent.children if parent else roots).append(e)
        stack.append((indent, e))
    return roots


def walk(entries):
    for e in entries:
        if isinstance(e, Entry):
            yield e
            yield from walk(e.children)


# ---------------------------------------------------------------- sidebar

def rel(href, from_page):
    """Link to wiki-relative href from wiki-relative page path."""
    target, _, anchor = href.partition('#')
    r = posixpath.relpath(posixpath.normpath(target), posixpath.dirname(from_page) or '.')
    return r + ('#' + anchor if anchor else '')


def entries_of(e):
    return [c for c in e.children if isinstance(c, Entry) and not c.hidden]


def nav_html(page, home):
    """Build the sidebar for `page` (an Entry). Columns:
    - the main categories (children of the wiki home), always
    - if the page has sub-pages: the page's own level, then its sub-pages
    - otherwise: its parent's level, then its own level
    Levels that would repeat the category row are skipped."""
    chain = []
    e = page
    while e is not None and e is not home:
        chain.append(e)
        e = e.parent
    if e is None:          # not under the wiki home
        return None
    chain.reverse()        # chain[0] is the category, chain[-1] is the page
    depth = len(chain)     # 0 = wiki home, 1 = category, ...

    def level_of(entry):   # siblings list containing entry
        return entries_of(entry.parent)

    cols = [entries_of(home)]
    kids = entries_of(page) if page is not home else []
    if page is not home:
        if kids:
            if depth >= 2:
                cols.append(level_of(page))
            cols.append(kids)
        else:
            if depth >= 3:
                cols.append(level_of(page.parent))
            if depth >= 2:
                cols.append(level_of(page))

    ancestors = {a.path for a in chain[:-1]}
    out = ['<nav>']
    for col in cols:
        out.append('<ul>')
        for c in col:
            cls = ''
            if c is page or (c.path == page.path and '#' not in c.href):
                cls = ' class="self"'
            elif c.path in ancestors and '#' not in c.href:
                cls = ' class="parent"'
            out.append(f'<li><a href="{html.escape(rel(c.href, page.path))}"{cls}>{html.escape(c.label)}</a></li>')
        out.append('</ul>')
    out.append('</nav>')
    return '\n'.join(out)


# ---------------------------------------------------------------- sitemap

def sitemap_html(roots):
    pages = {e.path for e in walk(roots) if e.path.lower().endswith(('.html', '.htm'))}

    def emit(items, depth):
        ind = '\t' * depth
        lines = [ind + '<ul>']
        for c in items:
            if isinstance(c, Heading):
                lines.append(f'{ind}\t<p>{html.escape(c.text)}:</p>')
                continue
            s = f'{ind}\t<li><a href="{html.escape(c.href)}">{html.escape(c.long_label)}</a>'
            if c.children:
                s += '\n' + emit(c.children, depth + 2) + '\n' + ind + '\t'
            lines.append(s + '</li>')
        lines.append(ind + '</ul>')
        return '\n'.join(lines)

    return (f'{SITEMAP_START}\n<p>This wiki links to <i>{len(pages)}</i> pages.</p>\n'
            + emit(roots, 0) + f'\n{SITEMAP_END}')


# ---------------------------------------------------------------- checks

A_RE = re.compile(r'<a\b[^>]*?\bhref\s*=\s*(["\'])(.*?)\1', re.I | re.S)
STRIP_RE = re.compile(r'<(script|textarea|style)\b.*?</\1\s*>', re.I | re.S)


def broken_links(page_file, text):
    found = []
    base = os.path.dirname(page_file)
    for m in A_RE.finditer(STRIP_RE.sub('', text)):
        href = m.group(2).strip()
        if not href or href.startswith(('#', 'mailto:', 'tel:', 'javascript:')) or re.match(r'^[a-z][a-z0-9+.-]*:|^//', href, re.I):
            continue
        path = unquote(href.split('#')[0].split('?')[0])
        if not path:
            continue
        target = os.path.normpath(os.path.join(base, path))
        if os.path.isdir(target):
            target = os.path.join(target, 'index.html')
        if not os.path.exists(target):
            found.append(href)
    return found


# ---------------------------------------------------------------- main

def main():
    roots = read_lexicon()
    entries = list(walk(roots))
    home = next((e for e in entries if e.path == HOME), None)
    if home is None:
        fail(f'lexicon.txt must contain the wiki home page "{HOME}".')

    # Every page in the lexicon must exist before anything is written.
    missing = [e for e in entries if not os.path.isfile(os.path.join(WIKI, e.path))]
    if missing:
        fail('these pages are in lexicon.txt but the file does not exist:\n' +
             '\n'.join(f'  line {e.line}: {e.href}' for e in missing))

    homes = {}
    for e in entries:
        if not e.alias and '#' not in e.href:
            if e.path in homes:
                print(f'WARNING: {e.href} is listed twice (lines {homes[e.path].line} and {e.line}). '
                      f'Its sidebar uses line {homes[e.path].line}. Start the other line with "= " to mark it as an extra link.')
            else:
                homes[e.path] = e

    changed, no_nav = [], []
    done = set()
    for e in entries:
        p = e.path
        if e.alias or p in done or p.startswith('..') or '#' in e.href or not p.lower().endswith(('.html', '.htm')):
            continue
        done.add(p)
        f = os.path.join(WIKI, p)
        text = open(f, encoding='utf-8', errors='surrogateescape').read()
        new = text
        # Only the wiki sidebar is replaced: a bare <nav> on a page that uses main.css.
        # A <nav class="..."> is the page's own menu and is left alone.
        if re.search(r'<nav>', text, re.I) and 'main.css' in text:
            nav = nav_html(e, home)
            if nav:
                new = re.sub(r'<nav>.*?</nav\s*>', lambda m: nav, new, count=1, flags=re.I | re.S)
        else:
            no_nav.append(p)
        if p == SITEMAP:
            block = sitemap_html(roots)
            if SITEMAP_START in new and SITEMAP_END in new:
                a = new.index(SITEMAP_START)
                b = new.index(SITEMAP_END) + len(SITEMAP_END)
                new = new[:a] + block + new[b:]
            else:
                print(f'WARNING: {SITEMAP} has no "{SITEMAP_START}" marker, so the sitemap was not updated.')
        if new != text:
            open(f, 'w', encoding='utf-8', errors='surrogateescape').write(new)
            changed.append(p)

    # Report.
    listed = {e.path for e in entries}
    unlisted, broken = [], []
    for d, dirs, files in os.walk(WIKI):
        for name in sorted(files):
            if not name.lower().endswith(('.html', '.htm')) or name.startswith('_'):
                continue
            f = os.path.join(d, name)
            p = os.path.relpath(f, WIKI).replace(os.sep, '/')
            if p not in listed:
                unlisted.append(p)
            for href in broken_links(f, open(f, encoding='utf-8', errors='replace').read()):
                broken.append(f'  {p}  ->  {href}')

    print(f'Updated {len(changed)} page(s)' + (':' if changed else '.'))
    for p in changed:
        print('  ' + p)
    if broken:
        print(f'\nBroken links ({len(broken)}):')
        print('\n'.join(broken))
    if unlisted:
        print(f'\nWiki pages not in lexicon.txt ({len(unlisted)}), so they get no sidebar and are not on the sitemap:')
        print('  ' + ', '.join(unlisted))
    if '-v' in sys.argv and no_nav:
        print(f'\nPages in lexicon.txt without a <nav> (left alone): {", ".join(no_nav)}')
    print('\nDone. Check the pages in your browser, then commit and push as usual.')


if __name__ == '__main__':
    main()
